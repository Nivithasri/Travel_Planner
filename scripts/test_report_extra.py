"""Extra cuts of the one-shot test run, from the saved eval/ablation/test_merged_<row>.json files
(no retrieval, no judgments read, no new run):

    python scripts/test_report_extra.py   # rewrites the "Additional cuts" section of test_final.md

Adds src_types@10 and the per-query-type and freshness-slice nDCG@10 that plan.md Phase 4/6 ask
for, and labels the rows: the FROZEN row is primary; the full chain is "best observed on test,
selected after seeing test" (D96 amended, D97).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "eval" / "ablation"
MARK = "## Additional cuts (generated by scripts/test_report_extra.py from test_merged_*.json)"
ROWS = ["bm25_plain", "dense_plain", "bm25_contextual", "dense_contextual", "hybrid_plain",
        "hybrid_contextual", "expanded_hybrid", "row7_rerank", "row8_mmr", "row9_crag"]
LABEL = {"dense_contextual": "dense_contextual (FROZEN, primary)",
         "row9_crag": "row9_crag (full chain; best observed on test, selected after seeing test)",
         "row7_rerank": "row7_rerank (observed on test; not selected)"}


def f3(v) -> str:
    return "-" if v is None else f"{v:.3f}"


def main() -> int:
    res = {n: json.loads((OUT / f"test_merged_{n}.json").read_text(encoding="utf-8"))["groups"]
           for n in ROWS}
    types = sorted(k for k in res[ROWS[0]] if k.startswith("type="))
    cols = ["overall", "freshness_slice", *types]
    n_q = {c: res[ROWS[0]][c]["n_queries"] for c in cols}
    lines = [MARK, "",
             "Status of the rows: the frozen pipeline is dense_contextual (primary). The full "
             "chain is shown as the best observed on test, selected after seeing test; choosing "
             "it now would be test-informed (D97).", "",
             "| row | src_types@10 | " + " | ".join(f"{c} (n={n_q[c]})" for c in cols) + " |",
             "|---|---|" + "---|" * len(cols)]
    for n in ROWS:
        g = res[n]
        lines.append(f"| {LABEL.get(n, n)} | {f3(g['overall']['src_types@10'])} | "
                     + " | ".join(f3(g[c]["ndcg@10"]) for c in cols) + " |")
    lines += ["", "Cells are mean nDCG@10 on the test queries of that group, merged judgments "
              "(round 1 human + round 2 chat, D95). Small groups (n of 1 to 4) are descriptive "
              "only; the freshness slice measures time-sensitive wording, not freshness (D32)."]
    path = OUT / "test_final.md"
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if MARK in text:
        text = text[:text.index(MARK)].rstrip("\n") + "\n"
    path.write_text(text.rstrip("\n") + "\n\n" + "\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
