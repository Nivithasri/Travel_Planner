"""The hand-written reference itineraries (app/reference_examples.py, D133): the inputs that match
them, the label that must travel with them, and the numbers in them that come from the real planner.
No model, no network."""
import datetime
import re

import pytest

from app import reference_examples as R
from app import state as S
from src.agents.planner import Candidate, plan_trip
from src.agents.state import ParsedRequest
from src.tools.check_season import check_season
from src.tools.travel_time import travel_time

REG = None


def prepared(**kw):
    global REG
    REG = REG or S.load_registry()
    return S.prepare(S.PlanForm(**kw), REG).overrides


HAMPI = dict(duration_days=3, budget_tier="mid", party="group", start_city="Bangalore",
             start_date=datetime.date(2026, 11, 4), constraints="no night travel",
             named_places=["Badami", "Hampi"])
COAST = dict(duration_days=4, budget_tier="mid", party="couple", start_city="Chennai",
             start_date=datetime.date(2026, 12, 10), interests=["temples", "beaches"],
             named_places=["Mahabalipuram", "Pondicherry"])
MADURAI = dict(duration_days=2, budget_tier="mid", party="group", start_city="Coimbatore",
               start_date=datetime.date(2026, 12, 4), interests=["temples"],
               named_places=["Madurai"])
KOCHI = dict(duration_days=3, budget_tier="mid", party="group",
             start_date=datetime.date(2026, 1, 15), interests=["food", "heritage"],
             named_places=["Kochi"])
CASES = {"hampi_badami": HAMPI, "coast": COAST, "madurai": MADURAI, "kochi": KOCHI}


@pytest.mark.parametrize("ref_id", list(CASES))
def test_each_reference_matches_exactly_its_own_inputs(ref_id):
    got = R.match(prepared(**CASES[ref_id]))
    assert got is not None and got.id == ref_id
    others = [k for k in CASES if k != ref_id]
    assert all(R.match(prepared(**CASES[k])).id != ref_id for k in others)


def test_places_and_interests_in_any_order_and_either_spelling_of_bangalore_match():
    assert R.match(prepared(**{**HAMPI, "named_places": ["Hampi", "Badami"]})).id == "hampi_badami"
    assert R.match(prepared(**{**HAMPI, "start_city": "Bengaluru"})).id == "hampi_badami"
    assert R.match(prepared(**{**HAMPI, "start_city": "bangalore"})).id == "hampi_badami"
    assert R.match(prepared(**{**COAST, "interests": ["beaches", "temples"]})).id == "coast"
    assert R.match(prepared(**{**KOCHI, "start_date": datetime.date(2027, 1, 31)})).id == "kochi"


@pytest.mark.parametrize("change", [
    {"duration_days": 4}, {"budget_tier": "luxury"}, {"party": "family"},
    {"start_date": datetime.date(2026, 12, 4)},  # a different month
    {"start_date": None}, {"start_city": "Chennai"}, {"constraints": ""},
    {"interests": ["wildlife"]}, {"named_places": ["Hampi"]}, {"end_city": "Chennai"},
    {"max_daily_travel_hours": 6.5},
])
def test_any_other_input_does_not_match(change):
    assert R.match(prepared(**{**HAMPI, **change})) is None


def test_a_kochi_request_with_a_start_city_or_other_interests_does_not_match():
    assert R.match(prepared(**{**KOCHI, "start_city": "Chennai"})) is None
    assert R.match(prepared(**{**KOCHI, "interests": ["food"]})) is None
    assert R.match({}) is None and R.match(None) is None


def test_the_banner_says_the_text_is_not_generated_and_the_legend_explains_the_dagger():
    assert "not generated by this system" in R.BANNER and "No model" in R.BANNER
    assert "dagger" in R.LEGEND and "not in the project's sources" in R.LEGEND
    assert R.by_id("kochi").id == "kochi" and R.by_id("nope") is None and R.by_id("") is None


@pytest.mark.parametrize("ref", R.REFERENCES, ids=lambda r: r.id)
def test_every_reference_is_laid_out_like_the_page_and_defines_the_markers_it_uses(ref):
    t = ref.text
    assert t.startswith("# South India itinerary") and "## Route, season and budget" in t
    assert "(estimate)" in t and "## Backup options" in t and "## Pages the facts come from" in t
    used = set(re.findall(r"\[(S\d+)\]", t.split("## Pages the facts come from")[0]))
    defined = set(re.findall(r"^- \[(S\d+)\]", t, re.M))
    assert used and used <= defined
    days = re.findall(r"^## Day (\d+):", t, re.M)
    assert days == [str(i) for i in range(1, ref.spec["duration_days"] + 1)]


@pytest.mark.parametrize("ref_id", list(CASES))
def test_the_computed_lines_equal_what_the_real_planner_gives(ref_id):
    """The route, season and budget lines were taken from the planner; this keeps them honest."""
    ref = R.by_id(ref_id)
    spec = CASES[ref_id]
    names = spec["named_places"]
    card = {"evidence_class": "full", "hill": False, "visibility_tercile": 1}
    cands = [Candidate(n, "TN", 0.5, 0.0, True, card) for n in names]
    req = ParsedRequest(
        named_places=list(names), duration_days=spec["duration_days"],
        budget_tier=spec["budget_tier"], party=spec["party"], month=spec["start_date"].month,
        start_city=spec.get("start_city"),
        constraints=[spec["constraints"]] if spec.get("constraints") else [])
    plan = plan_trip(req, cands, hours=travel_time, season=check_season)
    assert plan.feasible
    for leg in plan.legs:
        if leg.hours > 0:
            assert f"{leg.origin} to {leg.destination}, about {leg.hours:g} h by road" in ref.text
    assert f"about INR {plan.budget['total']:,} in total" in ref.text
    if spec.get("start_city") or len(names) > 1:
        assert ref.text.count("(provisional)") == sum(1 for leg in plan.legs if leg.hours > 0)
