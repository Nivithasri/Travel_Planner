def match(overrides: dict) -> Reference | None:
    """The reference whose inputs equal these overrides exactly (places and interests in any
    order, city names ignoring case), else None."""
    got = _norm(overrides or {})
    return next((r for r in REFERENCES if r.spec == got), None)


def by_id(ref_id: str) -> Reference | None:
    return next((r for r in REFERENCES if r.id == ref_id), None)
